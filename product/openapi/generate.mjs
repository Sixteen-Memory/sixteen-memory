import { readFile, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
import SwaggerParser from "@apidevtools/swagger-parser";
import openapiTS, { astToString } from "openapi-typescript";
import { document } from "./document.mjs";

await SwaggerParser.validate(structuredClone(document));
const json = JSON.stringify(document, null, 2) + "\n";
const types = "// Generated by product/openapi/generate.mjs. Do not edit.\n" +
  astToString(await openapiTS(structuredClone(document), { alphabetize: true, defaultNonNullable: false }));
for (const [path, content] of [
  ["./openapi.json", json], ["../sdk/openapi.json", json], ["../sdk/schema.d.ts", types],
]) {
  const url = new URL(path, import.meta.url);
  if (process.argv.includes("--check")) assert.equal(await readFile(url, "utf8"), content, `${path} is stale; run npm run generate in product/openapi.`);
  else await writeFile(url, content);
}
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} OpenAPI and SDK types (${Object.keys(document.paths).length} paths).`);
